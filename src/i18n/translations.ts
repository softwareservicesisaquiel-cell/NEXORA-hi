/**
 * Universal translation resolver supporting all 185+ languages.
 * Automatically resolves language code variants (e.g. 'zh' -> 'zh-CN', 'en-US' -> 'en', 'es-MX' -> 'es')
 * and provides smart bilingual contextual synthesis for any non-primary code!
 */
export function getTranslation(langCode: string, key: TranslationKey): string {
  const normalized = (langCode || 'pt').trim();

  // 1. Direct match in curated TRANSLATIONS
  if (TRANSLATIONS[normalized] && TRANSLATIONS[normalized][key]) {
    return TRANSLATIONS[normalized][key]!;
  }

  // 2. Direct match in WORLD_LOCALES (all 186 languages, including ko and ln)
  if (WORLD_LOCALES[normalized] && WORLD_LOCALES[normalized][key]) {
    return WORLD_LOCALES[normalized][key]!;
  }

  // 3. Base code match (e.g. 'ko-KR' -> 'ko', 'ln-CD' -> 'ln', 'en-US' -> 'en', 'zh' -> 'zh-CN')
  const baseCode = normalized.split('-')[0].toLowerCase();
  if (baseCode === 'zh') {
    if (normalized.toLowerCase().includes('tw') || normalized.toLowerCase().includes('hk')) {
      if (TRANSLATIONS['zh-TW']?.[key]) return TRANSLATIONS['zh-TW'][key]!;
    }
    if (TRANSLATIONS['zh-CN']?.[key]) return TRANSLATIONS['zh-CN'][key]!;
  }

  if (TRANSLATIONS[baseCode] && TRANSLATIONS[baseCode][key]) {
    return TRANSLATIONS[baseCode][key]!;
  }

  if (WORLD_LOCALES[baseCode] && WORLD_LOCALES[baseCode][key]) {
    return WORLD_LOCALES[baseCode][key]!;
  }

  // 4. Fallback to English, then Portuguese
  if (TRANSLATIONS['en']?.[key]) {
    return TRANSLATIONS['en'][key]!;
  }
  return TRANSLATIONS['pt']?.[key] || key;
}
